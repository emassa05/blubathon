REPO_ROOT = Path(__file__).resolve().parents[2]
OUTPUT_DIR = REPO_ROOT / "packages" / "shared" / "generated"

BANNER = "// Generated by `python -m tools.contracts.generate`. Do not edit by hand."
JSON_BANNER = "Generated by `python -m tools.contracts.generate`. Do not edit by hand."


# --------------------------------------------------------------------------
# JSON Schema
# --------------------------------------------------------------------------


def build_schema() -> dict[str, Any]:
    """One bundle with every published model under `$defs`."""

    targets = [(model, "serialization") for model in PUBLISHED_MODELS.values()]
    _, schema = models_json_schema(targets, ref_template="#/$defs/{model}")
    defs = dict(sorted(schema.get("$defs", {}).items()))
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "$id": f"https://blubathon.local/schema/{CONTRACT_VERSION}.json",
        "title": "Blubathon contract",
        "description": JSON_BANNER,
        "x-blubathon-contract-version": CONTRACT_VERSION,
        "x-blubathon-domain-version": DOMAIN_VERSION,
        "x-blubathon-published-models": sorted(PUBLISHED_MODELS),
        "$defs": defs,
    }


def schema_hash(schema: dict[str, Any]) -> str:
    """Domain-separated hash of the schema bundle, published in the handoff."""

    return content_hash(SCHEMA_ARTIFACT, CONTRACT_VERSION, schema)


# --------------------------------------------------------------------------
# Shared helpers for the TypeScript emitters
# --------------------------------------------------------------------------


def _ref_name(node: dict[str, Any]) -> str | None:
    ref = node.get("$ref")
    if isinstance(ref, str) and ref.startswith("#/$defs/"):
        return ref.removeprefix("#/$defs/")
    return None


def _is_enum_def(node: dict[str, Any]) -> bool:
    return "enum" in node and "properties" not in node


def _dependencies(node: Any, found: set[str]) -> set[str]:
    if isinstance(node, dict):
        name = _ref_name(node)
        if name is not None:
            found.add(name)
        for value in node.values():
            _dependencies(value, found)
    elif isinstance(node, list):
        for value in node:
            _dependencies(value, found)
    return found


def _topological_order(defs: dict[str, Any]) -> list[str]:
    """Emit a definition after everything it references, so `const` order works."""

    remaining = dict(defs)
    emitted: list[str] = []
    seen: set[str] = set()
    while remaining:
        progressed = False
        for name in sorted(remaining):
            deps = _dependencies(remaining[name], set()) - {name}
            if deps <= seen:
                emitted.append(name)
                seen.add(name)
                del remaining[name]
                progressed = True
        if not progressed:
            # A reference cycle. Emit the rest alphabetically; the Zod emitter
            # wraps every reference in `z.lazy`, so cycles still resolve.
            emitted.extend(sorted(remaining))
            break
    return emitted


def _json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False)


# --------------------------------------------------------------------------
# TypeScript types
# --------------------------------------------------------------------------


def _ts_type(node: dict[str, Any]) -> str:
    name = _ref_name(node)
    if name is not None:
        return name
    if "const" in node:
        return _json(node["const"])
    if "enum" in node:
        return " | ".join(_json(value) for value in node["enum"])
    if "anyOf" in node:
        return " | ".join(_ts_type(option) for option in node["anyOf"])
    if "oneOf" in node:
        return " | ".join(_ts_type(option) for option in node["oneOf"])

    kind = node.get("type")
    if kind == "array":
        items = node.get("items")
        inner = _ts_type(items) if isinstance(items, dict) else "unknown"
        return f"Array<{inner}>"
    if kind == "object":
        if "properties" in node:
            return _ts_object(node)
        additional = node.get("additionalProperties")
        if isinstance(additional, dict):
            return f"Record<string, {_ts_type(additional)}>"
        return "Record<string, unknown>"
    if kind == "string":
        return "string"
    if kind in {"number", "integer"}:
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "null":
        return "null"
    return "unknown"


def _ts_object(node: dict[str, Any], indent: str = "  ") -> str:
    required = set(node.get("required", []))
    lines = ["{"]
    for prop, schema in node.get("properties", {}).items():
        optional = "" if prop in required else "?"
        lines.append(f"{indent}{prop}{optional}: {_ts_type(schema)};")
    lines.append(indent[:-2] + "}")
    return "\n".join(lines)


def _ts_doc(node: dict[str, Any], indent: str = "") -> list[str]:
    description = node.get("description")
    if not description:
        return []
    lines = [f"{indent}/**"]
    lines += [f"{indent} * {line}".rstrip() for line in description.splitlines()]
    lines.append(f"{indent} */")
    return lines


def render_types(schema: dict[str, Any]) -> str:
    defs = schema["$defs"]
    out = [BANNER, "", f"// contract_version: {CONTRACT_VERSION}", ""]
    for name in sorted(defs):
        node = defs[name]
        out += _ts_doc(node)
        if _is_enum_def(node):
            union = " | ".join(_json(value) for value in node["enum"])
            out.append(f"export type {name} = {union};")
            members = ",\n".join(
                f"  {str(value).upper().replace('-', '_').replace('.', '_')}: {_json(value)}"
                for value in node["enum"]
            )
            out.append(f"export const {name}Values = {{\n{members},\n}} as const;")
        elif node.get("type") == "object" and "properties" in node:
            out.append(f"export interface {name} {_ts_object(node)}")
        else:
            out.append(f"export type {name} = {_ts_type(node)};")
        out.append("")
    return "\n".join(out)


# --------------------------------------------------------------------------
# Zod schemas
# --------------------------------------------------------------------------


def _zod_string(node: dict[str, Any]) -> str:
    expr = "z.string()"
    fmt = node.get("format")
    if fmt == "uuid":
        expr += ".uuid()"
    elif fmt == "date-time":
        expr += ".datetime({ offset: true })"
    elif fmt == "date":
        expr += ".regex(/^\\d{4}-\\d{2}-\\d{2}$/)"
    elif fmt == "uri":
        expr += ".url()"
    if "pattern" in node:
        expr += f".regex(new RegExp({_json(node['pattern'])}))"
    if "minLength" in node:
        expr += f".min({node['minLength']})"
    if "maxLength" in node:
        expr += f".max({node['maxLength']})"
    return expr


def _zod_number(node: dict[str, Any]) -> str:
    expr = "z.number()"
    if node.get("type") == "integer":
        expr += ".int()"
    if "minimum" in node:
        expr += f".gte({node['minimum']})"
    if "maximum" in node:
        expr += f".lte({node['maximum']})"
    if "exclusiveMinimum" in node:
        expr += f".gt({node['exclusiveMinimum']})"
    if "exclusiveMaximum" in node:
        expr += f".lt({node['exclusiveMaximum']})"
    return expr


def _zod_type(node: dict[str, Any]) -> str:
    name = _ref_name(node)
    if name is not None:
        return f"z.lazy(() => {name}Schema)"
    if "const" in node:
        return f"z.literal({_json(node['const'])})"
    if "enum" in node:
        values = node["enum"]
        if len(values) == 1:
            return f"z.literal({_json(values[0])})"
        return f"z.enum([{', '.join(_json(value) for value in values)}])"
    options = node.get("anyOf") or node.get("oneOf")
    if options:
        rendered = ", ".join(_zod_type(option) for option in options)
        return f"z.union([{rendered}])"

    kind = node.get("type")
    if kind == "array":
        items = node.get("items")
        inner = _zod_type(items) if isinstance(items, dict) else "z.unknown()"
        expr = f"z.array({inner})"
        if "minItems" in node:
            expr += f".min({node['minItems']})"
        if "maxItems" in node:
            expr += f".max({node['maxItems']})"
        return expr
    if kind == "object":
        if "properties" in node:
            return _zod_object(node)
        additional = node.get("additionalProperties")
        inner = _zod_type(additional) if isinstance(additional, dict) else "z.unknown()"
        return f"z.record(z.string(), {inner})"
    if kind == "string":
        return _zod_string(node)
    if kind in {"number", "integer"}:
        return _zod_number(node)
    if kind == "boolean":
        return "z.boolean()"
    if kind == "null":
        return "z.null()"
    return "z.unknown()"


def _zod_object(node: dict[str, Any], indent: str = "  ") -> str:
    required = set(node.get("required", []))
    lines = ["z.object({"]
    for prop, schema in node.get("properties", {}).items():
        expr = _zod_type(schema)
        if prop not in required:
            expr += ".optional()"
        lines.append(f"{indent}{_json(prop)}: {expr},")
    closing = indent[:-2] + "})"
    if node.get("additionalProperties") is False:
        closing += ".strict()"
    lines.append(closing)
    return "\n".join(lines)


def render_zod(schema: dict[str, Any]) -> str:
    defs = schema["$defs"]
    out = [
        BANNER,
        "",
        'import { z } from "zod";',
        "",
        f"// contract_version: {CONTRACT_VERSION}",
        "",
    ]
    for name in _topological_order(defs):
        node = defs[name]
        out.append(f"export const {name}Schema = {_zod_type(node)};")
        out.append("")
    return "\n".join(out)


