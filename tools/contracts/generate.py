def render_constants() -> str:
    entries = []
    for constant_id in sorted(CONSTANTS):
        spec = CONSTANTS[constant_id]
        value = list(spec.value) if isinstance(spec.value, tuple) else spec.value
        entries.append(
            "  "
            + _json(spec.constant_id)
            + ": { name: "
            + _json(spec.name)
            + ", value: "
            + _json(value)
            + ", decisionClass: "
            + _json(spec.decision_class)
            + (", note: " + _json(spec.note) if spec.note else "")
            + " },"
        )
    versions = {
        "contractVersion": CONTRACT_VERSION,
        "domainVersion": DOMAIN_VERSION,
        "formPolicyVersion": FORM_POLICY_VERSION,
        "defaultsEstimatorVersion": DEFAULTS_ESTIMATOR_VERSION,
        "scenarioSchemaVersion": SCENARIO_SCHEMA_VERSION,
        "scenarioBuilderVersion": SCENARIO_BUILDER_VERSION,
    }
    lines = [
        BANNER,
        "",
        "/** Registry C01-C50. A policy number is labelled as policy. */",
        "export const BLUBATHON_CONSTANTS = {",
        *entries,
        "} as const;",
        "",
        "export const BLUBATHON_VERSIONS = " + _json(versions) + " as const;",
        "",
    ]
    return "\n".join(lines)


def render_field_catalog() -> str:
    fields = []
    for code in CANONICAL_FIELD_ORDER:
        spec = FIELD_CATALOG[code]
        entry: dict[str, Any] = {
            "code": str(code),
            "kind": str(spec.kind),
            "allowedSources": sorted(str(source) for source in spec.allowed_sources),
            "defaultAllowed": spec.default_allowed,
        }
        values = spec.allowed_values()
        if values is not None:
            entry["allowedValues"] = list(values)
        if spec.minimum is not None:
            entry["minimum"] = spec.minimum
        if spec.maximum is not None:
            entry["maximum"] = spec.maximum
        if spec.max_length is not None:
            entry["maxLength"] = spec.max_length
        fields.append(entry)

    payload = {
        "canonicalOrder": [str(code) for code in CANONICAL_FIELD_ORDER],
        "fields": fields,
        "defaultAllowlistV1": sorted(str(code) for code in DEFAULT_ALLOWLIST_V1),
        "highSignalNoDefault": sorted(str(code) for code in HIGH_SIGNAL_NO_DEFAULT),
        "monitoredFields": [str(code) for code in MONITORED_FIELDS],
        "monitoredFieldPriority": {
            str(code): priority for code, priority in MONITORED_FIELD_PRIORITY.items()
        },
        "dqiRequiredFields": [str(code) for code in DQI_REQUIRED_FIELDS],
        "scenarioAllowlistV1": sorted(str(code) for code in SCENARIO_ALLOWLIST_V1),
    }
    return "\n".join(
        [
            BANNER,
            "",
            "/** The frontend only shows fields the session source is allowed to report. */",
            "export const BLUBATHON_FIELD_CATALOG = "
            + json.dumps(payload, ensure_ascii=False, indent=2)
            + " as const;",
            "",
        ]
    )


