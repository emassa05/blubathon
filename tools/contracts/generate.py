"""Generate JSON Schema and TypeScript/Zod from the Pydantic source of truth.

There is exactly one contract. The Pydantic models in `packages/shared` define
it; everything under `packages/shared/generated/` is derived and is never edited
by hand.

    python -m tools.contracts.generate
    git diff --exit-code packages/shared/generated

The constants, field catalogue and Spanish copy are emitted too, so the frontend
reads the same numbers, the same source matrix and the same wording instead of
keeping a second copy that can drift.
"""

