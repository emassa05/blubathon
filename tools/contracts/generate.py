# Entry point
# --------------------------------------------------------------------------


def generate_in_memory() -> dict[str, str]:
    """Render every artifact and return the file contents keyed by filename."""

    schema = build_schema()
    return {
        "blubathon.schema.json": (
            json.dumps(schema, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
        ),
        "contract.ts": render_types(schema),
        "contract.zod.ts": render_zod(schema),
        "constants.ts": render_constants(),
        "field-catalog.ts": render_field_catalog(),
        "texts.ts": render_texts(),
        "index.ts": render_index(),
        "contract.lock.json": render_lock(schema),
    }


def generate(output_dir: Path = OUTPUT_DIR) -> dict[str, str]:
    """Write the artifacts to disk with stable LF newlines."""

    artifacts = generate_in_memory()
    output_dir.mkdir(parents=True, exist_ok=True)
    for filename, content in artifacts.items():
        (output_dir / filename).write_text(content, encoding="utf-8", newline="\n")
    return artifacts


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Generate the Blubathon contract artifacts.")
    parser.add_argument("--output-dir", type=Path, default=OUTPUT_DIR)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the committed artifacts differ from what would be generated",
    )
    args = parser.parse_args(argv)

    schema = build_schema()
    digest = schema_hash(schema)
    if args.check:
        stale = []
        for filename, content in generate_in_memory().items():
            path = args.output_dir / filename
            if not path.is_file() or path.read_text(encoding="utf-8") != content:
                stale.append(filename)
        if stale:
            print("stale generated artifacts: " + ", ".join(sorted(stale)))
            return 1
        print(f"generated artifacts are current (schema_hash {digest})")
        return 0

    generate(args.output_dir)
    print(f"wrote {len(PUBLISHED_MODELS)} published models to {args.output_dir}")
    print(f"contract_version {CONTRACT_VERSION}")
    print(f"schema_hash {digest}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
